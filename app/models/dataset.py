"""SQLAlchemy model for the ``datasets`` table.

Each row represents a point-in-time snapshot of an Azure AD tenant's role
assignments, group memberships, and sign-in activity.  Datasets are the
root entity in the data model — audits and query logs reference them via
foreign keys.

Design notes
------------
* ``raw_data`` is stored as JSONB so that PostgreSQL can index into the
  document if needed in future phases, and to avoid a costly JSON ↔ text
  round-trip on every read.
* ``role_count`` is nullable because the column is populated by the
  ingestion service after parsing the raw payload; the database itself
  cannot compute it at INSERT time without a trigger.
* ``created_at`` defaults to the current UTC timestamp at the database
  level via ``server_default`` so that the value is reliable even when
  rows are inserted outside of the ORM (e.g. the seed script, migrations).
"""

from __future__ import annotations

import uuid
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from app.models.audit import Audit
from datetime import datetime

from sqlalchemy import DateTime, Integer, String, func, text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base


class Dataset(Base):
    """Persisted Azure AD role-assignment snapshot.

    Attributes
    ----------
    id:
        Universally unique identifier generated by the application layer
        (``uuid.uuid4()``) so that callers know the ID before the INSERT
        is committed.
    name:
        Human-readable label for the dataset, e.g.
        ``"Contoso tenant snapshot 2025-06-01"``.
    raw_data:
        The full JSON payload as uploaded by the caller.  Stored as JSONB
        for efficient storage and potential future indexing.
    user_count:
        Number of user/principal objects present in the dataset.  Derived
        by the ingestion service and stored here to avoid re-parsing the
        JSONB blob on every status query.
    role_count:
        Number of distinct roles referenced across all assignments in the
        dataset.  Nullable for the same reason as ``user_count``.
    created_at:
        UTC timestamp set by the database server on INSERT.  Using
        ``server_default`` ensures consistency even for rows inserted via
        raw SQL (seed script, test fixtures).
    """

    __tablename__ = "datasets"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
        comment="Unique dataset identifier (UUIDv4).",
    )
    name: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        comment="Human-readable dataset label.",
    )
    raw_data: Mapped[dict] = mapped_column(
        JSONB,
        nullable=False,
        comment="Full JSON payload as ingested from the caller.",
    )
    user_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        comment="Number of principals in the dataset.",
    )
    role_count: Mapped[int | None] = mapped_column(
        Integer,
        nullable=True,
        comment="Number of distinct roles referenced in the dataset.",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        comment="UTC timestamp of dataset ingestion.",
    )

    # ------------------------------------------------------------------
    # Relationships
    # ------------------------------------------------------------------

    #: All audit runs that reference this dataset.
    audits: Mapped[list[Audit]] = relationship(  # type: ignore[name-defined]
        "Audit",
        back_populates="dataset",
        cascade="all, delete-orphan",
        lazy="select",
    )

    def __repr__(self) -> str:  # pragma: no cover
        return (
            f"Dataset(id={self.id!r}, name={self.name!r}, "
            f"user_count={self.user_count!r}, created_at={self.created_at!r})"
        )
