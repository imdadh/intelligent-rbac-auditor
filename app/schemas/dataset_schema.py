"""Canonical schema definitions for the synthetic Azure AD dataset JSON format.

This module defines the structure of a point-in-time Azure AD tenant snapshot
as used throughout the RBAC Policy Auditor.  Every ingested dataset — whether
generated by the synthetic data script or uploaded via the API — must conform
to these definitions.

Top-level structure
-------------------
A dataset payload is a JSON object with four required top-level arrays:

:users:
    The principals under analysis.  Covers human users, service principals,
    and (optionally) on-premises synced accounts.  Each entry carries
    identity attributes, account status, and a ``userPrincipalName``.

:roleAssignments:
    Every direct or group-inherited directory role assignment active in the
    tenant at snapshot time.  Includes the role definition ID/name, the
    principal it applies to, whether the assignment is direct or inherited
    through a group, and the timestamp the assignment was created.

:signInLogs:
    A condensed activity log: one entry per sign-in event capturing
    successful and failed interactive sign-in events over the observation
    window (typically 90 days).  Non-interactive token acquisitions are
    out of scope for Phase 1.

:groups:
    Security and role-assignable groups, including their membership lists
    and any directory roles assigned directly to the group object.

Design notes
------------
* All identifier fields (``id``, ``principalId``, ``roleDefinitionId``,
  ``groupId``) use the UUID string format matching Azure AD object IDs.
* Timestamps use ISO 8601 / RFC 3339 UTC strings
  (``"2024-11-03T14:22:00Z"``).  The ingestion service normalises these
  to timezone-aware Python ``datetime`` objects before persistence.
* ``assignmentType`` is a controlled vocabulary: ``"direct"`` when the
  role is assigned to the principal directly, ``"group"`` when it is
  inherited through group membership.  The ``assignedVia`` field carries
  the group display name in the ``"group"`` case and is ``null`` (or
  omitted) for direct assignments.
* ``userType`` mirrors the Azure AD ``userType`` claim: ``"Member"`` for
  internal accounts, ``"Guest"`` for B2B guests, and
  ``"ServicePrincipal"`` for application/managed-identity principals.
* ``status`` in ``signInLogs`` is a short classification string:
  ``"Success"`` or ``"Failure"``.

Real Azure AD role definition IDs (built-in roles used in synthetic data)
-------------------------------------------------------------------------
The following GUIDs match the immutable Azure AD built-in role definition IDs.
Using real GUIDs keeps the synthetic data meaningful to engineers who work
with Entra ID and ensures the tier classification logic stays aligned with
actual tenant data::

    Global Administrator          62e90394-69f5-4237-9190-012177145e10
    Privileged Role Administrator fe930be7-5e62-47db-91af-98c3a49a38b1
    User Administrator            fe930be7-5e62-47db-91af-98c3a49a38b1
    Security Administrator        194ae4cb-b126-40b2-bd5b-6091b380977d
    Exchange Administrator        29232cdf-9323-42fd-ade2-1d097af3e4de
    SharePoint Administrator      f28a1f50-f6e7-4571-818b-6a12f2af6b6c
    Compliance Administrator      17315797-102d-40b4-93e0-432062caca18
    Helpdesk Administrator        729827e3-9c14-49f7-bb1b-9608f156bbb8
    Application Administrator     9b895d92-2cd3-44c7-9d02-a6ac2d5ea5c3
    Cloud Application Administrator 158c047a-c907-4556-b7ef-446551a6b5f7
    Directory Readers             88d8e3e3-8f55-4a1e-953a-9b9898b8876b
    Security Reader               5d6b6bb7-de71-4623-b4af-96380a352509
    Reports Reader                4a5d8f65-41da-4de4-8968-e035b65339cf
    Guest Inviter                 95e79109-95c0-4d8e-aee3-d01accf2d47b
    Message Center Reader         790c1fb9-7f7d-4f88-86a1-ef1f95c05c1b
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# users[]
# ---------------------------------------------------------------------------


class UserRecord(BaseModel):
    """A single principal entry in the ``users`` array.

    Attributes
    ----------
    id:
        Azure AD object ID (UUID string).  Serves as the join key for
        ``roleAssignments.principalId`` and ``signInLogs.userId``.
    displayName:
        Human-readable name shown in the Azure portal, e.g.
        ``"Alice Johnson"`` or ``"svc-backup-agent"``.
    userPrincipalName:
        UPN or application ID URI.  For service principals this is
        typically the application's client ID or a synthetic identifier
        such as ``"svc-backup@contoso.onmicrosoft.com"``.
    userType:
        Principal category.  One of ``"Member"``, ``"Guest"``, or
        ``"ServicePrincipal"``.
    accountEnabled:
        Whether the account is currently active.  Disabled accounts
        are still included so that dormant-assignment detection can
        flag standing privilege on blocked principals.
    """

    id: str = Field(description="Azure AD object ID (UUID format) of the principal.")
    displayName: str = Field(description="Human-readable display name of the principal.")
    userPrincipalName: str = Field(description="User principal name or application identifier URI.")
    userType: Literal["Member", "Guest", "ServicePrincipal"] = Field(
        description="Principal category: Member, Guest, or ServicePrincipal."
    )
    accountEnabled: bool = Field(
        description="True when the account is active; False when disabled."
    )


# ---------------------------------------------------------------------------
# roleAssignments[]
# ---------------------------------------------------------------------------


class RoleAssignmentRecord(BaseModel):
    """A single directory role assignment entry.

    Attributes
    ----------
    id:
        Unique identifier for this specific role assignment record.  May
        be the Azure AD role assignment object ID or a synthetic UUID.
    principalId:
        Object ID of the user, service principal, or group that holds
        the role.  Foreign key into ``users[].id`` (or ``groups[].id``
        for group-to-role assignments).
    roleDefinitionId:
        The immutable Azure AD role definition ID (UUID).  Stable across
        tenants for built-in roles.  See the module docstring for the
        full mapping of role names to definition IDs.
    roleName:
        Human-readable role display name, e.g.
        ``"Global Administrator"``.
    assignmentType:
        ``"direct"`` when the role is assigned directly to the principal;
        ``"group"`` when it is inherited through group membership.
    assignedVia:
        Display name of the group through which the role is inherited.
        Present only when ``assignmentType == "group"``; ``null``
        otherwise.  Using the display name (rather than the group ID)
        keeps the data human-readable in audit reports.
    assignedAt:
        ISO 8601 UTC timestamp recording when the role assignment was
        created in the tenant.  Used to compute assignment age and
        surface long-standing privilege grants.
    """

    id: str = Field(description="Unique identifier for this role assignment record.")
    principalId: str = Field(description="Object ID of the principal that holds the role.")
    roleDefinitionId: str = Field(description="Immutable Azure AD role definition UUID.")
    roleName: str = Field(description="Human-readable role display name.")
    assignmentType: Literal["direct", "group"] = Field(
        description="How the role is held: direct assignment or group inheritance."
    )
    assignedVia: str | None = Field(
        default=None,
        description=(
            "Display name of the group through which the role is inherited. "
            "Null for direct assignments."
        ),
    )
    assignedAt: str = Field(description="ISO 8601 UTC timestamp when the assignment was created.")


# ---------------------------------------------------------------------------
# signInLogs[]
# ---------------------------------------------------------------------------


class SignInLogRecord(BaseModel):
    """A condensed sign-in activity entry.

    One record represents a single sign-in event for a given user against
    a specific application.  The ingestion service aggregates these
    records to derive the most-recent sign-in timestamp per principal,
    which feeds directly into dormancy detection.

    Attributes
    ----------
    id:
        Unique identifier for this log entry.
    userId:
        Object ID of the signing-in user.  Foreign key into
        ``users[].id``.
    userDisplayName:
        Denormalised display name at the time of the sign-in event,
        included to make log inspection easier without a join.
    signInTimestamp:
        ISO 8601 UTC timestamp of the sign-in event.
    appDisplayName:
        The application the user authenticated against, e.g.
        ``"Microsoft Azure Management"`` or ``"Microsoft Teams"``.
    status:
        Outcome of the sign-in attempt: ``"Success"`` or ``"Failure"``.
    ipAddress:
        Source IP address of the sign-in request.  May be anonymised
        (e.g. ``"198.51.100.0"``) in synthetic data.
    """

    id: str = Field(description="Unique identifier for this sign-in log entry.")
    userId: str = Field(description="Object ID of the user who signed in.")
    userDisplayName: str = Field(description="Display name of the user at the time of sign-in.")
    signInTimestamp: str = Field(description="ISO 8601 UTC timestamp of the sign-in event.")
    appDisplayName: str = Field(
        description="Display name of the application accessed during sign-in."
    )
    status: Literal["Success", "Failure"] = Field(description="Outcome of the sign-in attempt.")
    ipAddress: str = Field(description="Source IP address of the sign-in request.")


# ---------------------------------------------------------------------------
# groups[]
# ---------------------------------------------------------------------------


class GroupRecord(BaseModel):
    """A security or role-assignable group.

    Attributes
    ----------
    id:
        Azure AD object ID of the group.  Referenced by
        ``roleAssignments[].principalId`` when the group itself holds a
        role, and by ``roleAssignments[].assignedVia`` (by name) when
        a user inherits a role through this group.
    displayName:
        Human-readable group name, e.g. ``"Security Operations"`` or
        ``"Global Admins (PIM-eligible)"``.
    isRoleAssignable:
        True when the group is a role-assignable group (i.e. created with
        the ``isAssignableToRole`` flag).  Role-assignable groups carry
        higher privilege-escalation risk because they can hold directory
        roles.
    members:
        Array of principal object IDs (from ``users[].id``) that belong
        to this group.  Nested group memberships are pre-flattened for
        Phase 1 — each user's effective membership is expanded at
        generation time so the pipeline does not need to recurse.
    assignedRoles:
        Array of role definition IDs (from
        ``roleAssignments[].roleDefinitionId``) that are assigned
        directly to this group object.  When non-empty, every member of
        the group inherits these roles via ``assignmentType="group"``
        entries in ``roleAssignments[]``.
    """

    id: str = Field(description="Azure AD object ID of the group.")
    displayName: str = Field(description="Human-readable group display name.")
    isRoleAssignable: bool = Field(
        default=False,
        description="True when the group is flagged as role-assignable in Azure AD.",
    )
    members: list[str] = Field(
        default_factory=list,
        description="List of member principal object IDs belonging to this group.",
    )
    assignedRoles: list[str] = Field(
        default_factory=list,
        description="List of role definition IDs assigned directly to this group.",
    )


# ---------------------------------------------------------------------------
# Top-level dataset payload
# ---------------------------------------------------------------------------


class AzureADDatasetPayload(BaseModel):
    """Top-level structure of a synthetic Azure AD tenant snapshot.

    This is the schema validated on every ``POST /api/v1/datasets`` request
    and produced by ``scripts/generate_synthetic_data.py``.  All four arrays
    are required; empty arrays are permitted but will produce no findings.

    Attributes
    ----------
    users:
        All principals in scope for this snapshot.  Must include every
        principal referenced by ``roleAssignments[].principalId``.  The
        array should cover the full mix of Member users, Guest users, and
        ServicePrincipal accounts present in the tenant.
    roleAssignments:
        Every active directory role assignment at snapshot time.  Includes
        both direct assignments and group-inherited assignments (with
        ``assignedVia`` populated for the latter).  A single user may
        appear in multiple entries if they hold several roles.
    signInLogs:
        Interactive sign-in events for the observation window (up to 90
        days prior to snapshot).  May be empty for principals that have
        never signed in; the absence of any log entry is itself a signal
        for dormancy detection.  Multiple entries per user are expected —
        one per sign-in event.
    groups:
        Security and role-assignable groups.  Required even when no group
        assignments exist so that the ingestion service can resolve group
        membership for inherited assignment lineage.

    Cross-reference invariants
    --------------------------
    The following consistency rules are enforced during ingestion validation:

    1. Every ``roleAssignments[].principalId`` must match either a
       ``users[].id`` or a ``groups[].id``.
    2. Every ``signInLogs[].userId`` must match a ``users[].id``.
    3. Every ``groups[].members`` element must match a ``users[].id``.
    4. When ``roleAssignments[].assignmentType == "group"``, the
       ``assignedVia`` field must be non-null and should correspond to
       a ``groups[].displayName``.

    These invariants are validated by ``app/services/ingestion.py`` and
    reported as structured errors (FR-2).

    Example
    -------
    A minimal valid payload::

        {
            "users": [
                {
                    "id": "00000000-0000-0000-0000-000000000001",
                    "displayName": "Alice Johnson",
                    "userPrincipalName": "alice@contoso.onmicrosoft.com",
                    "userType": "Member",
                    "accountEnabled": true
                }
            ],
            "roleAssignments": [
                {
                    "id": "ra-00000001",
                    "principalId": "00000000-0000-0000-0000-000000000001",
                    "roleDefinitionId": "62e90394-69f5-4237-9190-012177145e10",
                    "roleName": "Global Administrator",
                    "assignmentType": "direct",
                    "assignedVia": null,
                    "assignedAt": "2023-06-15T09:00:00Z"
                }
            ],
            "signInLogs": [
                {
                    "id": "sl-00000001",
                    "userId": "00000000-0000-0000-0000-000000000001",
                    "userDisplayName": "Alice Johnson",
                    "signInTimestamp": "2024-10-01T08:30:00Z",
                    "appDisplayName": "Microsoft Azure Management",
                    "status": "Success",
                    "ipAddress": "203.0.113.42"
                }
            ],
            "groups": []
        }
    """

    users: list[UserRecord] = Field(description="All principals in scope for this snapshot.")
    roleAssignments: list[RoleAssignmentRecord] = Field(
        description="All active directory role assignments at snapshot time."
    )
    signInLogs: list[SignInLogRecord] = Field(
        description="Interactive sign-in events for the observation window."
    )
    groups: list[GroupRecord] = Field(
        description="Security and role-assignable groups in the tenant."
    )


# ---------------------------------------------------------------------------
# Role tier classification constants
# ---------------------------------------------------------------------------

#: Tier 0 — highest privilege.  Compromise of any Tier 0 role grants
#: effective control over the entire Azure AD tenant.  These roles are
#: the primary targets for dormancy and overprivilege detection.
ROLE_TIER_0: frozenset[str] = frozenset(
    {
        "Global Administrator",
        "Privileged Role Administrator",
        "Privileged Authentication Administrator",
    }
)

#: Tier 1 — elevated privilege.  These roles grant broad write access
#: to significant portions of the tenant (users, groups, applications,
#: compliance data) and represent meaningful lateral-movement risk.
ROLE_TIER_1: frozenset[str] = frozenset(
    {
        "User Administrator",
        "Security Administrator",
        "Exchange Administrator",
        "SharePoint Administrator",
        "Compliance Administrator",
        "Application Administrator",
        "Cloud Application Administrator",
        "Authentication Administrator",
        "Helpdesk Administrator",
        "License Administrator",
        "Groups Administrator",
        "Teams Administrator",
    }
)

#: Tier 2 — read-only or narrowly scoped roles.  Low standalone risk;
#: should not normally trigger findings unless combined with unusual
#: activity patterns.
ROLE_TIER_2: frozenset[str] = frozenset(
    {
        "Directory Readers",
        "Security Reader",
        "Reports Reader",
        "Message Center Reader",
        "Guest Inviter",
        "Directory Writers",
        "Billing Administrator",
    }
)


def classify_role_tier(role_name: str) -> int:
    """Return the privilege tier (0, 1, or 2) for a given role display name.

    Unknown roles default to tier 2 (lowest risk) so that the pipeline
    does not silently escalate unfamiliar role names to a higher tier.
    Callers that need strict validation should check the return value
    against the known tier sets.

    Parameters
    ----------
    role_name:
        The human-readable role display name, e.g.
        ``"Global Administrator"``.

    Returns
    -------
    int
        0, 1, or 2 indicating the privilege tier.
    """
    if role_name in ROLE_TIER_0:
        return 0
    if role_name in ROLE_TIER_1:
        return 1
    return 2


